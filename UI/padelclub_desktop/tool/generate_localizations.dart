import 'dart:convert';
import 'dart:io';

/// Run from UI/padelclub_desktop after editing assets/l10n/*.json.
/// Embedding messages keeps startup synchronous in both distribution targets.
void main() {
  final english = Map<String, String>.from(
    jsonDecode(File('assets/l10n/en.json').readAsStringSync()),
  );
  final bosnian = Map<String, String>.from(
    jsonDecode(File('assets/l10n/bs.json').readAsStringSync()),
  );
  if (english.length != bosnian.length ||
      !english.keys.every(bosnian.containsKey)) {
    throw StateError('English and Bosnian message IDs must match.');
  }
  String literal(String text) => jsonEncode(text).replaceAll(r'$', r'\$');
  final output = StringBuffer(
    '// Generated by tool/generate_localizations.dart. Do not edit directly.\n'
    'const bosnianMessages = <String, String>{\n',
  );
  for (final key in english.keys) {
    output.writeln('  ${literal(key)}: ${literal(bosnian[key]!)},');
  }
  output.writeln('};');
  File(
    'lib/core/localization/bosnian_messages.dart',
  ).writeAsStringSync(output.toString());
  stdout.writeln('Generated ${bosnian.length} Bosnian messages.');
}
